import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, it, before, after } from 'node:test'
import {
  detectLockfile,
  isYarnBerry,
  lockfileAt,
  readProjectManifest
} from '../../src/parsers/detect.ts'

const tmpBase = mkdtempSync(join(tmpdir(), 'semver-ranger-detect-'))

after(() => {
  rmSync(tmpBase, { recursive: true, force: true })
})

describe('detectLockfile', () => {
  before(() => {
    mkdirSync(join(tmpBase, 'npm-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'npm-project', 'package-lock.json'), '{"lockfileVersion":3}')

    mkdirSync(join(tmpBase, 'pnpm-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'pnpm-project', 'pnpm-lock.yaml'), 'lockfileVersion: "6.0"\n')

    mkdirSync(join(tmpBase, 'yarn-classic-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'yarn-classic-project', 'yarn.lock'), '# yarn lockfile v1\n')

    mkdirSync(join(tmpBase, 'yarn-berry-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'yarn-berry-project', 'yarn.lock'), '__metadata:\n  version: 6\n')

    mkdirSync(join(tmpBase, 'shrinkwrap-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'shrinkwrap-project', 'npm-shrinkwrap.json'), '{}')

    mkdirSync(join(tmpBase, 'both-npm-project'), { recursive: true })
    writeFileSync(join(tmpBase, 'both-npm-project', 'package-lock.json'), '{}')
    writeFileSync(join(tmpBase, 'both-npm-project', 'npm-shrinkwrap.json'), '{}')
  })

  // Regression: a project locked only with a shrinkwrap had "no lockfile".
  it('detects an npm shrinkwrap', () => {
    const dir = join(tmpBase, 'shrinkwrap-project')
    assert.deepStrictEqual(detectLockfile(dir), {
      path: join(dir, 'npm-shrinkwrap.json'),
      type: 'npm',
      manager: 'npm'
    })
  })

  // npm ignores package-lock.json when a shrinkwrap exists, so analysing it was wrong.
  it('prefers the shrinkwrap over package-lock.json, as npm does', () => {
    const dir = join(tmpBase, 'both-npm-project')
    assert.strictEqual(detectLockfile(dir)?.path, join(dir, 'npm-shrinkwrap.json'))
  })

  it('detects npm lockfile', () => {
    const result = detectLockfile(join(tmpBase, 'npm-project'))
    assert.ok(result)
    assert.strictEqual(result.type, 'npm')
    assert.strictEqual(result.manager, 'npm')
  })

  it('detects pnpm lockfile', () => {
    const result = detectLockfile(join(tmpBase, 'pnpm-project'))
    assert.ok(result)
    assert.strictEqual(result.type, 'pnpm')
    assert.strictEqual(result.manager, 'pnpm')
  })

  it('detects yarn classic', () => {
    const result = detectLockfile(join(tmpBase, 'yarn-classic-project'))
    assert.ok(result)
    assert.strictEqual(result.type, 'yarn-classic')
    assert.strictEqual(result.manager, 'yarn')
  })

  it('detects yarn berry', () => {
    const result = detectLockfile(join(tmpBase, 'yarn-berry-project'))
    assert.ok(result)
    assert.strictEqual(result.type, 'yarn-berry')
    assert.strictEqual(result.manager, 'yarn')
  })

  it('returns null when no lockfile found', () => {
    mkdirSync(join(tmpBase, 'empty'), { recursive: true })
    const result = detectLockfile(join(tmpBase, 'empty'))
    assert.strictEqual(result, null)
  })
})

describe('lockfileAt', () => {
  for (const [file, type, manager] of [
    ['npm-shrinkwrap.json', 'npm', 'npm'],
    ['package-lock.json', 'npm', 'npm'],
    ['pnpm-lock.yaml', 'pnpm', 'pnpm'],
    ['yarn.lock', 'yarn-classic', 'yarn']
  ]) {
    it(`maps ${file} to ${type}`, () => {
      const path = join(tmpBase, 'any', file)
      assert.deepStrictEqual(lockfileAt(path), { path, type, manager })
    })
  }

  it('reads a yarn.lock header to tell Berry from Classic', () => {
    const path = join(tmpBase, 'yarn-berry-project', 'yarn.lock')
    assert.strictEqual(lockfileAt(path)?.type, 'yarn-berry')
  })

  it('returns null for a name that is not a lockfile', () => {
    assert.strictEqual(lockfileAt(join(tmpBase, 'notes.txt')), null)
  })
})

describe('isYarnBerry', () => {
  it('detects a berry lockfile from its header', () => {
    const dir = join(tmpBase, 'berry')
    mkdirSync(dir, { recursive: true })
    const file = join(dir, 'yarn.lock')
    writeFileSync(
      file,
      '# This file is generated by running "yarn install" inside your project.\n' +
        '# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 6\n'
    )
    assert.strictEqual(isYarnBerry(file), true)
    rmSync(dir, { recursive: true, force: true })
  })

  it('looks for the marker only in the header', () => {
    const dir = join(tmpBase, 'classic')
    mkdirSync(dir, { recursive: true })
    const file = join(dir, 'yarn.lock')
    // __metadata: appears far past the 512-byte header and must not be matched.
    writeFileSync(file, `# yarn lockfile v1\n${'#'.repeat(2000)}\n__metadata:\n`)
    assert.strictEqual(isYarnBerry(file), false)
    rmSync(dir, { recursive: true, force: true })
  })

  it('returns false for a missing file', () => {
    assert.strictEqual(isYarnBerry(join(tmpBase, 'does-not-exist.lock')), false)
  })
})

describe('readProjectManifest', () => {
  it('treats a missing file as ordinary', () => {
    assert.deepStrictEqual(readProjectManifest(join(tmpBase, 'no-such-dir')), {
      deps: null,
      error: null
    })
  })

  it('reports an unparseable file', () => {
    const dir = join(tmpBase, 'broken')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'package.json'), '{ not json')
    const manifest = readProjectManifest(dir)
    assert.strictEqual(manifest.deps, null)
    assert.match(manifest.error ?? '', /JSON/u)
  })

  it('returns the parsed dependencies of a valid file', () => {
    const dir = join(tmpBase, 'valid')
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'package.json'), '{"dependencies":{"a":"^1"}}')
    assert.deepStrictEqual(readProjectManifest(dir), {
      deps: { dependencies: { a: '^1' } },
      error: null
    })
  })
})
